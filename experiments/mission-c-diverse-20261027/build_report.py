def read(path, default=None):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default

def text(path):
    return path.read_text(encoding="utf-8") if path.exists() else ""

def save(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

def file_evidence(path):
    return {"path": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "bytes": path.stat().st_size} if path.exists() else None

def result_brief(row, path):
    if row is None:
        return None
    return {**{k: v for k, v in row.items() if k not in {"biography", "page_text", "tool_text", "content_html"}},
            "full_result": str(path)}

def compare_quote(label, quote, source, outputs):
    verified = normalize(quote) in normalize(source)
    return {"section": label, "quote": quote, "source_verified": verified, "source_lines": location(source, quote),
            "methods": {method: {"status": quote_status(quote, source, value),
                "lines": location(value, quote)} for method, value in outputs.items()}}

